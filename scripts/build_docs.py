def gap_text() -> str:
    """Validation minus test balanced accuracy per model, from the test look's own record."""
    central = [e["val_pooled"]["balanced_accuracy"] - e["scores"]["pooled"]["balanced_accuracy"]
               for e in FULL["single_model_per_seed"]]  # fmt: skip
    e = FULL["ensemble_3_seeds"]
    ens = e["val_pooled"]["balanced_accuracy"] - e["scores"]["pooled"]["balanced_accuracy"]
    fed = {m: [x["val_pooled"]["balanced_accuracy"] - x["scores"]["pooled"]["balanced_accuracy"]
               for x in FULL["federated"][m]["per_seed"]] for m in ("fedavg", "fedprox")}  # fmt: skip
    higher = sum(d < 0 for v in fed.values() for d in v)
    return (f"{100 * min(central):.1f} to {100 * max(central):.1f} points lower on test than on "
            f"validation for the centralized single models and {100 * ens:.1f} points lower for "
            f"the ensemble; for the six federated models it is mixed ({higher} of 6 score higher "
            f"on test)")  # fmt: skip


